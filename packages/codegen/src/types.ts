import type { TypeSource } from "@nxlab/core";
import type { SchemaDirective } from "@nxlab/schema";

export type { TypeSource };

export interface CodegenModule {
  id: string;
  typeDefs: TypeSource | readonly TypeSource[];
}

export interface GenerateOptions {
  directives?: readonly SchemaDirective[];
}

export interface CodegenOptions {
  /** Root directory containing one direct child directory per module. */
  modules: string;
  /** Glob(s) for type definition files, resolved relative to each module directory. */
  typeDefs: string | string[];
  output: string;
  schema?: string;
  watch?: boolean;
  clear?: boolean;
  directives?: readonly SchemaDirective[];
  logs?: boolean;
}

export interface ClientCodegenOptions {
  /** A schema SDL file (such as the server's `schema` output), or a server URL to introspect. */
  schema: string;
  /** Glob(s) for the operations, `.graphql` or `.gql` files. */
  documents: string | string[];
  output: string;
  /** Sent when introspecting a URL, e.g. for a server that needs a token. */
  headers?: Record<string, string>;
  logs?: boolean;
}

export const BUILTIN_SCALARS: ReadonlySet<string> = new Set([
  "ID",
  "String",
  "Int",
  "Float",
  "Boolean"
]);

/** Names the generated file declares itself; schema types can't use them. */
export const RESERVED_NAMES: ReadonlySet<string> = new Set([
  "Application",
  "Maybe",
  "ResolveEnum",
  "ResolveScalar",
  "Scalars"
]);

export const HEADER =
  "// Generated by @nxlab/codegen - do not edit.\n// oxlint-disable no-redeclare";
